#!/usr/bin/env python3
"""Generate docs/compatibility.md: every action on every integration, its support level and the models its test
records tested.

A level comes from the records, never from a label: Verified when a passing record exists and the adapter is not
experimental, otherwise Experimental. Models come from each passing record's `| Device |` row. A group (a row with
no firmware, firmware `unknown`, or named Group or Zone) shows as "group", not as a model.

Usage: scripts/gen_compat.py [--check]

--check exits 1 when docs/compatibility.md differs from what the records generate.
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from custom_components.deviceside.core.registry import AdapterRegistry  # noqa: E402
from scripts.check_release import adapters, records  # noqa: E402

PAGE = REPO / "docs" / "compatibility.md"
RESULT = re.compile(r"^\| Result \| (\S+) \|", re.MULTILINE)
DEVICE = re.compile(r"^\| Device \| (.*) \|$", re.MULTILINE)
ENTRY = re.compile(r"^(?P<name>.*?)(?: \(`(?P<model>[^`]+)`\))?, firmware `(?P<firmware>[^`]+)`$")
GROUP_NAMES = {"group", "zone"}

HEADER = """\
# Compatibility

<!-- Generated by scripts/gen_compat.py from docs/test-records/. Do not edit; run the script. -->

DeviceSide was tested on the models below. Others may work. If yours isn't listed, please try it and
[report the result](https://github.com/jasonmx/DeviceSide/issues/new?template=device_report.yml), whether it works
or not.

**Verified**: a passing test record from a rig run. The models in the record are the ones tested.
**Experimental**: no current record. It may work, and it is not in a stable release.

A group is a native group of the integration (a Hue zone, a ZHA or Zigbee2MQTT group).
"""


def models(record: Path) -> list[str]:
    """The devices a record tested, as `model`, firmware or `group`, in the order the record lists them. A Device row
    that is missing or unreadable is an error, not an empty list: a silent gap would pass for a tested model."""
    if not (row := DEVICE.search(record.read_text())):
        raise SystemExit(f"{record.relative_to(REPO)}: no Device row")
    if row[1] == "none":
        return []
    found = []
    for item in row[1].split("; "):
        if entry := ENTRY.match(item.strip()):
            if entry["firmware"] == "unknown" or entry["name"].lower() in GROUP_NAMES:
                found.append("group")
            else:
                found.append(f"`{entry['model'] or entry['name']}`, firmware `{entry['firmware']}`")
        elif "group" in item.lower():
            found.append("group")
        else:
            raise SystemExit(f"{record.relative_to(REPO)}: can't read Device entry {item!r}")
    return found


def passing(integration: str, action: str) -> list[Path]:
    return [path for path in records(integration, action) if (m := RESULT.search(path.read_text())) and m[1] == "pass"]


def link(record: Path, action: str) -> str:
    option = record.stem.removeprefix(action).lstrip("-")
    label = option.replace("_", " ") if option else "record"
    return f"[{label}]({record.relative_to(REPO / 'docs').as_posix()})"


def row(action: str, adapter) -> str:
    found = passing(adapter.integration, action)
    level = "Verified" if found and not adapter.scope.experimental else "Experimental"
    tested: list[str] = []
    for record in found:
        for item in models(record):
            if item not in tested:
                tested.append(item)
    # Groups last, after the single devices.
    tested.sort(key=lambda item: item == "group")
    records_cell = ", ".join(link(record, action) for record in found)
    return f"| `{action}` | {level} | {'<br>'.join(tested) or 'none'} | {records_cell} | |"


def generate(registry: AdapterRegistry) -> str:
    by_integration: dict[str, list] = {}
    for _, adapter in adapters(registry):
        by_integration.setdefault(adapter.integration, []).append(adapter)
    parts = [HEADER]
    for key in sorted(by_integration, key=lambda key: registry.integrations[key].title):
        parts.append(f"## {registry.integrations[key].title}\n")
        parts.append("| Action | Level | Tested models | Records | Reported working |")
        parts.append("|---|---|---|---|---|")
        parts += [row(adapter.action, adapter) for adapter in sorted(by_integration[key], key=lambda a: a.action)]
        parts.append("")
    return "\n".join(parts)


def main(argv: list[str] | None = None, registry: AdapterRegistry | None = None, page: Path = PAGE) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the page is out of date")
    args = parser.parse_args(argv)

    text = generate(registry or AdapterRegistry.discover())
    if args.check:
        if not page.exists() or page.read_text() != text:
            print(f"error: {page.relative_to(REPO)} is out of date; run scripts/gen_compat.py", file=sys.stderr)
            return 1
        return 0
    page.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
