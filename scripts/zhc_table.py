#!/usr/bin/env python3
"""Generate the standard lights table and its page: the zigbee-herdsman-converters (ZHC) light definitions on ZHC's
standard converters, which Zigbee2MQTT's `standard_light` class keys on (docs/integrations/zigbee2mqtt/internals.md,
Standard lights; docs/evidence.md, Documented).

The table is the Zigbee catalog's `zigbee/standard_lights.py`. Between its markers, generated: the ZHC release pinned
and `MODELS`, a row per member definition model with the Zigbee strings ZHC matches it on (its zigbeeModel IDs and
fingerprints; a fingerprinted white label's are its own), formatted by ruff. Outside them, hand-kept and kept by every
regeneration: `EXCLUDED` (the split-offs, each with its source) and `KEPT` (a departure a maintainer kept, with the
reason). The page, docs/integrations/zigbee2mqtt/standard-lights.md, is rendered from it.

A member is a ZHC light definition, resolved with ZHC's own prepareDefinition (zhc_table/resolve.mjs), whose converter
for every key DeviceSide publishes is ZHC's standard one, with no `meta` flag that could touch a DeviceSide call
(`departures`): only the flags known to leave the calls alone may be set, so a flag ZHC adds keeps a definition out
until a maintainer has read it. A definition exposing `color_hs` without `supportsHueAndSaturation` is out, as its
saturation fade is `moveToColor`, not the call on record (docs/research/2026-11-25-z2m-converter-survey.md, Part 4).

--pin <tag>  Clone ZHC at the release tag, build it, rewrite the generated block and the page, and print the proposal
             for the bump PR's body: additions; departures, each **review** when the model was a member at the last
             full release, else **leaves**; and trait changes on the families' definitions, flagged, never
             classifying (which needs the previous pin built too). Needs git, node and network.
--check      No network: the table loads, every EXCLUDED and KEPT row has its source or reason, no model is in both or
             KEPT while a member, EXCLUDED names MODELS keys, PAIRS holds no key a split-off overlaps (`--write` drops
             them), and the page is current.
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from types import SimpleNamespace

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

TABLE = Path("custom_components/deviceside/zigbee/standard_lights.py")
PAGE = Path("docs/integrations/zigbee2mqtt/standard-lights.md")
RESOLVER = REPO / "scripts" / "zhc_table" / "resolve.mjs"
# The class sections of the Zigbee2MQTT page, which the page names for a light a family keeps.
DEVICES = REPO / "docs" / "integrations" / "zigbee2mqtt" / "devices.yaml"
ZHC = "https://github.com/Koenkk/zigbee-herdsman-converters"
BEGIN = "# BEGIN GENERATED by scripts/zhc_table.py --pin: don't edit by hand."
END = "# END GENERATED"
RELEASE_TAG = re.compile(r"v\d+\.\d+\.\d+")  # a full release of DeviceSide, no rc

# The meta flags that leave every DeviceSide call alone, each run on the converters in the survey (Part 1c): the hs
# path DeviceSide's color_hs check reads, endpoint-suffixed keys (a gang is refused: addressing.py), and flags on calls
# DeviceSide never sends. Any other flag set, false aside, keeps a definition out.
HARMLESS_META = frozenset(
    {
        "supportsHueAndSaturation",
        "multiEndpoint",
        "multiEndpointSkip",
        "applyRedFix",
        "disableActionGroup",
        "overrideHaDiscoveryPayload",
        "thermostat",
    }
)
HS_FLAG = "supportsHueAndSaturation"
# The actions an EXCLUDED row may name: the light actions the class serves (classes.py).
ACTIONS = frozenset(
    {
        "raise_brightness",
        "lower_brightness",
        "stop",
        "raise_hue",
        "lower_hue",
        "raise_saturation",
        "lower_saturation",
        "set_attributes",
        "get_attributes",
    }
)


def departures(row: Mapping) -> list[str]:
    """Why a resolved light definition is no member, empty for a member: each key whose converter isn't standard, and
    each flag that could touch a call."""
    found = [f"{key} converter overridden" for key in row["overrides"]]
    found += [
        f"meta {name}"
        for name, value in sorted(row["meta"].items())
        if name not in HARMLESS_META and value is not False
    ]
    if row["color_hs"] and row["meta"].get(HS_FLAG) is not True:
        found.append(f"color_hs without {HS_FLAG}")
    return found


# A member's row, as the table's `Light`: (vendor, color_hs, zigbee_models, fingerprints).
Row = tuple[str, bool, tuple[str, ...], tuple[tuple[str, str], ...]]


def _pairs(fingerprints: Iterable) -> tuple[tuple[str, str], ...]:
    return tuple(dict.fromkeys((str(model), str(manufacturer)) for model, manufacturer in fingerprints))


def published(row: Mapping) -> list[tuple[str, str, tuple[str, ...], tuple[tuple[str, str], ...]]]:
    """The (model, vendor, zigbee_models, fingerprints) a definition can be published under: its own, and each white
    label with a fingerprint, which Zigbee2MQTT names when the fingerprint matches (ZHC's findByDevice). Each has its
    own fingerprints (resolve.mjs leaves the white labels' out of the definition's)."""
    labels = [label for label in row["white_labels"] if label["fingerprinted"]]
    return [(row["model"], row["vendor"], tuple(dict.fromkeys(row["zigbee_models"])), _pairs(row["fingerprints"]))] + [
        (label["model"], label["vendor"], (), _pairs(label["fingerprints"])) for label in labels
    ]


Key = tuple[str, str]  # (model ID, manufacturer), "" where absent: a zigbeeModel z is (z, "")


def keys(zigbee_models: Iterable[str], fingerprints: Iterable[Key]) -> set[Key]:
    return {(zigbee_model, "") for zigbee_model in zigbee_models} | set(fingerprints)


def member_pairs(entries: Iterable[tuple[str, set[Key]]], member: Mapping[str, bool]) -> dict[Key, bool]:
    """Each key a member lists whose every definition is a member, with color_hs when all of them expose it
    (`member`: a member's model, not excluded, and its color_hs). A key's definitions are those listing it or a key
    it overlaps: for (m, mf), (m, "") and ("", mf); for (m, ""), any (m, *); for ("", mf), any (*, mf). That isn't
    ZHC's matcher, and (m, "") isn't checked against ("", mf)."""
    listing: dict[Key, set[str]] = {}
    for model, held in entries:
        for key in held:
            listing.setdefault(key, set()).add(model)
    by_model: dict[str, set[str]] = {}
    by_manufacturer: dict[str, set[str]] = {}
    for (model_id, manufacturer), models in listing.items():
        by_model.setdefault(model_id, set()).update(models)
        by_manufacturer.setdefault(manufacturer, set()).update(models)
    none: set[str] = set()

    def definitions(key: Key) -> set[str]:
        model_id, manufacturer = key
        if model_id and manufacturer:
            return listing[key] | listing.get((model_id, ""), none) | listing.get(("", manufacturer), none)
        if model_id:
            return by_model[model_id]
        return by_manufacturer[manufacturer] if manufacturer else none | {""}

    found = {}
    for key in listing:
        if (models := definitions(key)) and all(model in member for model in models):
            found[key] = all(member[model] for model in models)
    return dict(sorted(found.items()))


@dataclass(frozen=True)
class Resolved:
    """A ZHC release's table: its members, by model, as `Row`s; the model strings dropped as ambiguous
    (more than one definition publishes them, or a member's shares a model with a definition that isn't one); and
    each light definition's traits, by model, for the family check."""

    members: dict[str, Row]
    ambiguous: list[str]
    traits: dict[str, tuple]
    # The member keys (`member_pairs`), with color_hs.
    pairs: dict[Key, bool] = field(default_factory=dict)


def table(resolved: Mapping, excluded: Iterable[str] = ()) -> Resolved:
    """The members of one resolved ZHC release (resolve.mjs's output), and the member keys, none of an `excluded`
    model's."""
    seen: dict[str, list[tuple[Row | None, tuple]]] = {}
    for row in resolved["lights"]:
        member = not departures(row)
        traits = (tuple(departures(row)), row["color_hs"])
        for model, vendor, zigbee_models, fingerprints in published(row):
            entry = (vendor, row["color_hs"], zigbee_models, fingerprints)
            seen.setdefault(model, []).append((entry if member else None, traits))
    for model in resolved.get("other_models", ()):
        seen.setdefault(model, []).append((None, ()))
    members, ambiguous = {}, []
    for model, rows in seen.items():
        if len(rows) > 1:
            if any(entry is not None for entry, _ in rows):
                ambiguous.append(model)
        elif rows[0][0] is not None:
            members[model] = rows[0][0]
    traits = {model: rows[0][1] for model, rows in seen.items() if len(rows) == 1 and rows[0][1]}
    every = [
        (model, keys(zigbee_models, fingerprints))
        for row in [*resolved["lights"], *resolved.get("other_strings", ())]
        for model, _, zigbee_models, fingerprints in published(row)
    ]
    out = set(excluded)
    member = {model: row[1] for model, row in members.items() if model not in out}
    return Resolved(dict(sorted(members.items())), sorted(ambiguous), traits, member_pairs(every, member))


# The table module.


def load(text: str) -> SimpleNamespace:
    """The table module's names, from its text: stdlib only and no I/O, so it runs alone, at any git rev."""
    names: dict = {"__name__": "standard_lights"}
    exec(compile(text, str(TABLE), "exec"), names)  # noqa: S102 - the repo's own file
    return SimpleNamespace(**{name: value for name, value in names.items() if not name.startswith("__")})


def members(module: SimpleNamespace) -> frozenset[str]:
    return frozenset(
        (module.MODELS.keys() | {row.model for row in module.KEPT}) - {row.model for row in module.EXCLUDED}
    )


def block(
    pin: str,
    models: Mapping[str, Row],
    pairs: Mapping[Key, bool] | None = None,
) -> str:
    """The generated block, markers included, one row a line (`pin` runs ruff format on the file after)."""
    lines = [
        BEGIN,
        f"ZHC_RELEASE = {_str(pin)}",
        "# A member's definition model, with its row (Light).",
        "MODELS: dict[str, Light] = {",
        *(f"    {_str(model)}: Light{_literal(tuple(row))}," for model, row in sorted(models.items())),
        "}",
        "# The member keys: (model ID, manufacturer), with whether every definition under it exposes color_hs.",
        "PAIRS: dict[tuple[str, str], bool] = {",
        *(f"    {_literal(key)}: {hs!r}," for key, hs in sorted((pairs or {}).items())),
        "}",
        END,
    ]
    return "\n".join(lines)


def _str(text: str) -> str:
    """A Python string literal as the formatter writes it: double quotes."""
    return json.dumps(text, ensure_ascii=False)


def _literal(value) -> str:
    """A str, bool or tuple of them as a Python literal, strings in double quotes."""
    if isinstance(value, tuple):
        return "(" + ", ".join(map(_literal, value)) + ("," if len(value) == 1 else "") + ")"
    return _str(value) if isinstance(value, str) else repr(value)


def rewrite(text: str, pin: str, models: Mapping[str, Row], pairs: Mapping[Key, bool] | None = None) -> str:
    """The module text with its generated block replaced, the hand-kept text around it untouched."""
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + block(pin, models, pairs) + text[end:]


def prune(text: str) -> str:
    """The module text with PAIRS cut to `allowed`: a new split-off's keys, and those overlapping them, dropped
    offline, so a split-off needs no --pin."""
    module = load(text)
    allow = allowed(module)
    pairs = {key: hs and allow[key] for key, hs in module.PAIRS.items() if key in allow}
    return rewrite(text, module.ZHC_RELEASE, module.MODELS, pairs)


def allowed(module: SimpleNamespace) -> dict[Key, bool]:
    """`member_pairs` over the table's own rows (MODELS and KEPT, EXCLUDED's out): PAIRS may hold no other key, nor
    color_hs where this has none. The bump computes PAIRS over every ZHC definition, so it holds a subset."""
    out = {row.model for row in module.EXCLUDED}
    rows = [*module.MODELS.items(), *((row.model, row.light) for row in module.KEPT)]
    member = {model: row[1] for model, row in rows if model not in out}
    return member_pairs(((model, keys(row[2], row[3])) for model, row in rows), member)


# The page.


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def page(module: SimpleNamespace) -> str:
    """docs/integrations/zigbee2mqtt/standard-lights.md, from the table: the members, less those a family keeps
    (`family_sections`), which are listed apart."""
    kept = {row.model: row.light for row in module.KEPT}
    rows = {**module.MODELS, **kept}

    def order(model: str) -> tuple[str, str]:
        return rows[model][0].casefold(), model.casefold()

    families = family_sections({model: rows[model] for model in members(module)})
    listed = sorted(members(module) - families.keys(), key=order)
    release = module.ZHC_RELEASE
    lines = [
        "# Zigbee2MQTT's standard lights",
        "",
        "<!-- Generated by scripts/zhc_table.py from the table in"
        " custom_components/deviceside/zigbee/standard_lights.py: don't edit by hand. -->",
        "",
        f"From zigbee-herdsman-converters [{release}]({ZHC}/releases/tag/{release}).",
        "",
        "The lights DeviceSide places in Zigbee2MQTT's [standard lights](index.md#standard-lights) class: each a"
        " Zigbee2MQTT device definition that sends DeviceSide's calls through the converters Zigbee2MQTT uses for most"
        " lights, with no change for that model. To check yours, find the **Model** on its Zigbee2MQTT device page and"
        " look for it under Members. A light from a brand with a family of its own (Hue, IKEA, Tuya and the others on"
        " [the Zigbee2MQTT page](index.md)) stays in its family: those found here are under In a family, as far as"
        " the definition shows its brand.",
        "",
        f"## Members ({len(listed)})",
        "",
        "Smooth hue and saturation: whether the light takes hue and saturation moves (it exposes Zigbee2MQTT's"
        " `color_hs`).",
        "",
        "| Vendor | Model | Smooth hue and saturation |",
        "|---|---|---|",
        *(f"| {_cell(rows[m][0])} | {_cell(m)} | {'yes' if rows[m][1] else 'no'} |" for m in listed),
        "",
        f"## In a family ({len(families)})",
        "",
        "Lights whose definition qualifies, but whose family takes them first: they get the family's levels, on the"
        " section of the Zigbee2MQTT page it names.",
        "",
        "| Vendor | Model | Family |",
        "|---|---|---|",
        *(
            f"| {_cell(rows[m][0])} | {_cell(m)} | [{families[m]}](index.md#{_anchor(families[m])}) |"
            for m in sorted(families, key=order)
        ),
        "",
        "## Excluded",
        "",
        "Lights a report shows failing one of DeviceSide's calls. They stay with other brands' lights, behind the Labs"
        " option, on every action.",
        "",
        "| Vendor | Model | Action | Source |",
        "|---|---|---|---|",
        *(
            f"| {_cell(rows.get(row.model, ('',))[0])} | {_cell(row.model)} | `{row.action}` | <{row.source}> |"
            for row in sorted(module.EXCLUDED, key=lambda row: (row.model.casefold(), row.action))
        ),
    ]
    if module.KEPT:
        lines += [
            "",
            "## Kept",
            "",
            "Lights a ZHC release took off the list, which a maintainer kept, with the reason.",
            "",
            "| Vendor | Model | Reason |",
            "|---|---|---|",
            *(f"| {_cell(row.light[0])} | {_cell(row.model)} | {_cell(row.reason)} |" for row in module.KEPT),
        ]
    return "\n".join(lines) + "\n"


# --check.


def check(repo: Path = REPO) -> list[str]:
    """What's wrong with the committed table and page, with no network."""
    try:
        module = load((repo / TABLE).read_text())
    except (OSError, SyntaxError, NameError, AttributeError) as err:
        return [f"{TABLE} doesn't load: {err}"]
    problems = []
    if not isinstance(module.ZHC_RELEASE, str) or not module.ZHC_RELEASE.strip():
        problems.append("ZHC_RELEASE names no ZHC release")
    if not module.MODELS:
        problems.append("MODELS is empty")
    problems += row_problems(module) + pair_problems(module)
    if not problems:
        path = repo / PAGE
        if not path.exists() or path.read_text() != page(module):
            problems.append(f"{PAGE} is stale; run scripts/zhc_table.py --check --write")
    return problems


def row_problems(module: SimpleNamespace) -> list[str]:
    """The hand-kept rows' problems: an EXCLUDED row with no https source, an action the class doesn't serve or a model
    MODELS doesn't hold, a KEPT
    row with no reason or whose model is a member again, and a model in both."""
    problems = []
    for row in module.EXCLUDED:
        if not str(row.source).startswith("https://"):
            problems.append(f"EXCLUDED {row.model!r} has no https source")
        if row.action not in ACTIONS:
            problems.append(f"EXCLUDED {row.model!r} names {row.action!r}, not an action the class serves")
        if row.model not in module.MODELS:
            problems.append(f"EXCLUDED {row.model!r} is no MODELS key, so it excludes nothing")
    for row in module.KEPT:
        if not str(row.reason).strip():
            problems.append(f"KEPT {row.model!r} has no reason")
        if row.model in module.MODELS:
            problems.append(f"KEPT {row.model!r} is a member again: drop its row")
    if both := sorted({row.model for row in module.EXCLUDED} & {row.model for row in module.KEPT}):
        problems.append(f"both EXCLUDED and KEPT: {both}")
    return problems


def pair_problems(module: SimpleNamespace) -> list[str]:
    """PAIRS' problems, offline: a key `allowed` doesn't hold (a split-off's, one overlapping it, or one no member
    row lists), or color_hs where it has none. This catches a hand edit and a new split-off (`--check --write` drops
    its keys)."""
    allow = allowed(module)
    problems = []
    if found := sorted(set(module.PAIRS) - set(allow)):
        problems.append(
            f"PAIRS holds keys a split-off overlaps or no member row lists: {found};"
            " run scripts/zhc_table.py --check --write"
        )
    if found := sorted(key for key, hs in module.PAIRS.items() if hs and key in allow and not allow[key]):
        problems.append(f"PAIRS gives color_hs to keys of a row without it: {found}")
    return problems


# --pin.


def git(repo: Path, *args: str, check: bool = True) -> str:
    result = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=check)
    return result.stdout


def resolve(pin: str) -> dict:
    """Clone ZHC at the tag into a temp dir, install from its lockfile with the pnpm it names, build it, and resolve
    its light definitions (resolve.mjs)."""
    with tempfile.TemporaryDirectory(prefix="zhc-") as tmp:
        root = Path(tmp) / "zhc"
        clone = ["git", "-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1", "--branch", pin, ZHC + ".git"]
        # Progress to stderr: stdout is the proposal alone.
        subprocess.run([*clone, str(root)], check=True, stdout=sys.stderr)
        pnpm = json.loads((root / "package.json").read_text()).get("packageManager", "pnpm")
        for command in (["install", "--frozen-lockfile"], ["run", "build"]):
            subprocess.run(["npx", "-y", pnpm, *command], cwd=root, check=True, stdout=sys.stderr)
        out = subprocess.run(["node", str(RESOLVER), str(root)], check=True, capture_output=True, text=True)
        return json.loads(out.stdout)


def last_release(repo: Path) -> str | None:
    """The latest full DeviceSide release tag (no rc), or None; a clone with no tags at all is refused, as it would
    pass every departure as never released."""
    tags = git(repo, "tag", "--list", "v*", "--sort=-v:refname").split()
    if not tags:
        raise SystemExit(f"{repo} has no release tags: fetch them (git fetch --tags) before --pin")
    return next((tag for tag in tags if RELEASE_TAG.fullmatch(tag)), None)


def released_members(repo: Path) -> tuple[str | None, frozenset[str]]:
    """The members at the last full release, which shipped outside Labs: none before the table existed. Any other
    failure to read the table at the tag is refused, as it would skip every departure's review."""
    if (tag := last_release(repo)) is None:
        return None, frozenset()
    found = subprocess.run(
        ["git", "-C", str(repo), "show", f"{tag}:{TABLE.as_posix()}"], capture_output=True, text=True
    )
    if found.returncode == 0:
        return tag, members(load(found.stdout))
    if git(repo, "ls-tree", "--name-only", tag, "--", TABLE.as_posix()).strip():
        raise SystemExit(f"can't read {TABLE} at {tag}: {found.stderr.strip()}")
    return tag, frozenset()


def family_models(resolved: Mapping) -> dict[str, str]:
    """The light definitions DeviceSide's rules would place in a family, by model, with the class (`family_of`)."""
    found = {}
    for row in resolved["lights"]:
        if name := family_of(
            row["vendor"], row["model"], row["zigbee_models"], row["fingerprint_manufacturers"], row["exposes"]
        ):
            found[row["model"]] = name
    return found


def family_of(
    vendor: str, model: str, zigbee_models: Iterable[str], manufacturers: Iterable[str], exposes: Iterable[str] = ()
) -> str | None:
    """The family class DeviceSide's rules would place a definition in, or None: read off what the definition shows
    (its vendor and model in the registry, its Zigbee models, its fingerprints' manufacturers, its exposes), so an
    approximation. A definition rarely carries its Zigbee manufacturer, so each family that keys on one is tried with
    its vendor as one too, and IKEA's with IKEA's string."""
    from custom_components.deviceside.core.scope import OTHER  # noqa: PLC0415
    from custom_components.deviceside.integrations.zigbee2mqtt.classes import device_class  # noqa: PLC0415
    from custom_components.deviceside.zigbee.ikea import MANUFACTURER as IKEA_MANUFACTURER  # noqa: PLC0415
    from custom_components.deviceside.zigbee.standard_lights import STANDARD_LIGHT  # noqa: PLC0415

    registry = SimpleNamespace(manufacturer=vendor, model=None, model_id=model)
    guesses = {*manufacturers, vendor} | ({IKEA_MANUFACTURER} if vendor == "IKEA" else set())
    for manufacturer in sorted(guesses):
        for zigbee_model in list(zigbee_models) or [model]:
            bridge = {
                "zigbee_manufacturer": manufacturer,
                "zigbee_model": zigbee_model,
                "definition_model": model,
                "exposes": frozenset(exposes),
            }
            if (name := device_class(registry, bridge)) not in (OTHER, STANDARD_LIGHT):
                return name
    return None


def family_sections(rows: Mapping[str, Row]) -> dict[str, str]:
    """The rows a family keeps (`family_of`, on what the table holds: no exposes), by model, with the family class's
    section of the Zigbee2MQTT page (devices.yaml)."""
    import yaml  # noqa: PLC0415

    sections = {name: entry["section"] for name, entry in yaml.safe_load(DEVICES.read_text())["capabilities"].items()}
    found = {}
    for model, row in rows.items():
        zigbee_models = [*row[2], *(model_id for model_id, _ in row[3] if model_id)]
        if name := family_of(row[0], model, dict.fromkeys(zigbee_models), {mf for _, mf in row[3] if mf}):
            found[model] = sections[name]
    return found


def _anchor(heading: str) -> str:
    """GitHub's anchor for a heading."""
    return re.sub(r"[^\w\- ]", "", heading.casefold()).replace(" ", "-")


def proposal(
    pin: str,
    previous: str,
    old: Mapping[str, Row],
    new: Resolved,
    released: tuple[str | None, frozenset[str]],
    module: SimpleNamespace,
    family_changes: Iterable[str] = (),
) -> str:
    """The bump PR's body: what the regeneration changed, and what a maintainer must review."""
    tag, shipped = released
    added = sorted(new.members.keys() - old.keys())
    gone = sorted(old.keys() - new.members.keys())
    kept = {row.model for row in module.KEPT}
    lines = [
        f"## ZHC bump: {previous} to {pin}",
        "",
        f"Members: {len(new.members)} (was {len(old)}); {len(added)} added, {len(gone)} departing.",
        "",
        "### Additions",
        "",
        *([f"- {new.members[m][0]} `{m}`" for m in added] or ["None."]),
        "",
        "### Departures",
        "",
        f"**review**: a member at {tag}, so its features shipped outside Labs: keep it (a `KEPT` row, with the"
        " reason) or let it leave (an `EXCLUDED` row, with a source, if a report says why). **leaves**: no review."
        if tag
        else "No full release holds the table yet, so every departure **leaves**.",
        "",
        *(
            [f"- {'**review**' if m in shipped and m not in kept else '**leaves**'}: {old[m][0]} `{m}`" for m in gone]
            or ["None."]
        ),
        "",
        "### Trait changes on family models (flagged, never classifying)",
        "",
        *(list(family_changes) or ["None."]),
    ]
    if new.ambiguous:
        lines += ["", "### Left out as ambiguous", "", *(f"- `{m}`" for m in new.ambiguous)]
    if back := sorted(kept & new.members.keys()):
        lines += ["", "### Kept models that are members again (drop their KEPT rows)", "", *(f"- `{m}`" for m in back)]
    return "\n".join(lines) + "\n"


def family_trait_changes(old: Mapping, new: Mapping) -> list[str]:
    """Each family model whose traits (departures, color_hs) differ between the two resolved releases."""
    old_traits, new_traits = table(old).traits, table(new).traits
    families = {**family_models(old), **family_models(new)}
    lines = []
    for model, name in sorted(families.items()):
        before, after = old_traits.get(model), new_traits.get(model)
        if before != after:
            lines.append(f"- `{model}` ({name}): {_traits(before)} to {_traits(after)}")
    return lines


def _traits(traits: tuple | None) -> str:
    if traits is None:
        return "absent"
    flags, hs = traits
    return (", ".join(flags) or "standard") + ("; color_hs" if hs else "")


def pin(tag: str, repo: Path = REPO) -> str:
    """Regenerate the table and page at the ZHC release tag; the proposal."""
    path = repo / TABLE
    text = path.read_text()
    module = load(text)
    previous = module.ZHC_RELEASE
    resolved = resolve(tag)
    new = table(resolved, {row.model for row in module.EXCLUDED})
    changes = family_trait_changes(resolve(previous), resolved) if previous != tag else []
    body = proposal(tag, previous, module.MODELS, new, released_members(repo), module, changes)
    path.write_text(rewrite(text, tag, new.members, new.pairs))
    subprocess.run([sys.executable, "-m", "ruff", "format", "-q", str(path)], check=True)
    (repo / PAGE).write_text(page(load(path.read_text())))
    return body


def main(argv: list[str] | None = None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--pin", metavar="TAG", help="the ZHC release tag to regenerate at")
    group.add_argument("--check", action="store_true", help="check the table and page, no network")
    parser.add_argument(
        "--write", action="store_true", help="with --check: drop a split-off's PAIRS keys and rewrite a stale page"
    )
    args = parser.parse_args(argv)
    if args.pin:
        print(pin(args.pin, repo), end="")
        return 0
    if args.write:
        table_path = repo / TABLE
        if (pruned := prune(text := table_path.read_text())) != text:
            table_path.write_text(pruned)
            subprocess.run([sys.executable, "-m", "ruff", "format", "-q", str(table_path)], check=True)
        (repo / PAGE).parent.mkdir(parents=True, exist_ok=True)
        (repo / PAGE).write_text(page(load((repo / TABLE).read_text())))
    problems = check(repo)
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if not problems:
        print(f"{TABLE}: current, and its page too.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
