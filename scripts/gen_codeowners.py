#!/usr/bin/env python3
"""Generate .github/CODEOWNERS from each integration's `IntegrationInfo.maintainers`, and the device report's
Integration dropdown from their titles.

The repo maintainers own everything (`*`, first), so shared code, shared docs and the generated pages' shared inputs
(`docs/models.yaml`) need their review. Each integration's package then goes to its maintainers, with the repo
maintainers appended so they can always approve: its adapter package, its tests and test fixture, and its doc bundle
(`docs/integrations/<key>/`, its test records included), each only once it exists. GitHub reads the last matching
line, so the per-integration lines must follow `*`.

A family (`IntegrationInfo.families`) with maintainers of its own gets its paths after its integration's: its package,
its tests and its research folder, to its maintainers, then the integration's, then the repo's. A catalog file, which
the stacks' families of one key share, goes to those families' maintainers and their integrations'. The catalog's
shared files go to the maintainers of every integration that reads the catalog (has a family of a key with a catalog
file), never a family's: they word what every such family's devices are told. Their lines
follow the catalog's, so they win over a family keyed for one. Each of these lines is written only when it names an
owner the line enclosing it doesn't, so a family with `maintainers=()` adds none.

`REPO_MAINTAINERS` also has to match `manifest.json`'s `codeowners`, which HA shows as the integration's owners; the
script checks that, in both modes, and leaves the manifest for a hand edit.

The dropdown in `.github/ISSUE_TEMPLATE/device_report.yml` is the sorted titles of the available integrations,
written between its `# integrations:start` / `# integrations:end` comment lines; the catch-all after them stays
hand-written. `scripts/route_issue.py` routes a report on those titles.

Usage: scripts/gen_codeowners.py [--check]

--check exits 1 when a committed file differs from what this generates.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from custom_components.deviceside.core.registry import AdapterRegistry  # noqa: E402

CODEOWNERS = REPO / ".github" / "CODEOWNERS"
MANIFEST = REPO / "custom_components" / "deviceside" / "manifest.json"
DEVICE_REPORT = REPO / ".github" / "ISSUE_TEMPLATE" / "device_report.yml"
DROPDOWN = ("# integrations:start", "# integrations:end")
# What a title may hold, written as-is into a YAML option and a Markdown link: one line of letters, digits and plain
# punctuation, so no title adds a form field or markup to a generated part.
TITLE = re.compile(r"[^\W_][\w .+()/-]*(?<! )")
# The repo maintainers: admin on the repo, owners of shared code, merging any PR. The one source of their handles;
# manifest.json's codeowners must match it.
REPO_MAINTAINERS: tuple[str, ...] = ("jasonmx",)
# Each integration's paths, relative to the repo, by its key; a path that doesn't exist yet is left out.
PATHS = (
    "custom_components/deviceside/integrations/{key}/",
    "tests/integrations/{key}/",
    "tests/fixtures/{key}.py",
    "docs/integrations/{key}/",
)
# Each family's paths, by its integration's key and its own.
FAMILY_PATHS = (
    "custom_components/deviceside/integrations/{key}/families/{family}/",
    "tests/integrations/{key}/families/{family}/",
    "docs/integrations/{key}/research/{family}/",
)
# The catalog's paths, by the key of the families that share it.
CATALOG_PATHS = (
    "custom_components/deviceside/zigbee/{family}.py",
    "tests/zigbee/test_{family}.py",
)
# The catalog's files that no family key holds: the reasons the catalog-reading integrations' `refusals.py` share.
SHARED_CATALOG_PATHS = (
    "custom_components/deviceside/zigbee/reasons.py",
    "tests/zigbee/test_reasons.py",
)


def owners(*maintainers: str) -> str:
    return " ".join(f"@{handle}" for handle in dict.fromkeys([*maintainers, *REPO_MAINTAINERS]))


def lines_for(
    templates: tuple[str, ...], handles: list[str], enclosing: tuple[str, ...], repo: Path, **keys: str
) -> list[str]:
    """A line per existing path, or none when every handle is already an owner on the enclosing line."""
    if not set(handles) - set(enclosing) - set(REPO_MAINTAINERS):
        return []
    paths = [template.format(**keys) for template in templates]
    return [f"/{path} {owners(*handles)}" for path in paths if (repo / path).exists()]


def generate(registry: AdapterRegistry, repo: Path = REPO) -> str:
    if not REPO_MAINTAINERS:
        raise SystemExit("REPO_MAINTAINERS is empty: shared code would have no owner")
    lines = [
        "# Generated by scripts/gen_codeowners.py from each integration's IntegrationInfo.maintainers. Do not edit;",
        "# run the script. The last matching line wins, so everything not listed below is the repo maintainers'.",
        f"* {owners()}",
    ]
    # Each family key's owners across the integrations: the families' maintainers, then their integrations'.
    catalog: dict[str, tuple[list[str], list[str]]] = {}
    # The maintainers of each integration that reads the catalog: the shared files' owners.
    readers: list[str] = []
    for key in sorted(registry.integrations):
        info = registry.integrations[key]
        if not info.available:
            raise SystemExit(f"{key} failed to import ({info.unavailable_reason}); its maintainers can't be read")
        paths = [path.format(key=key) for path in PATHS]
        if not (repo / paths[0]).is_dir():
            raise SystemExit(f"{key}: no package at {paths[0]}")
        lines.append("")
        lines += [f"/{path} {owners(*info.maintainers)}" for path in paths if (repo / path).exists()]
        for family in sorted(info.families, key=lambda family: family.key):
            if not (repo / (package := FAMILY_PATHS[0].format(key=key, family=family.key))).is_dir():
                raise SystemExit(f"{key}: no package for family {family.key} at {package}")
            if (repo / CATALOG_PATHS[0].format(family=family.key)).exists():
                readers.extend(info.maintainers)
            handles = [*family.maintainers, *info.maintainers]
            lines += lines_for(FAMILY_PATHS, handles, info.maintainers, repo, key=key, family=family.key)
            shared = catalog.setdefault(family.key, ([], []))
            shared[0].extend(family.maintainers)
            shared[1].extend(info.maintainers)
    if shared_lines := [
        line
        for family, (theirs, integrations) in sorted(catalog.items())
        for line in lines_for(CATALOG_PATHS, [*theirs, *integrations], (), repo, family=family)
    ] + lines_for(SHARED_CATALOG_PATHS, readers, (), repo):
        lines += ["", *shared_lines]
    return "\n".join(lines) + "\n"


def plain_title(info) -> str:
    """The integration's title, after checking it is plain text; raises SystemExit otherwise."""
    if not TITLE.fullmatch(info.title):
        raise SystemExit(f"IntegrationInfo title {info.title!r} isn't one line of letters, digits and ` .+()/-`")
    return info.title


def generate_device_report(text: str, registry: AdapterRegistry) -> str:
    """The form with its Integration options replaced by the registry's titles, one per line, sorted."""
    start, end = DROPDOWN
    lines = text.splitlines(keepends=True)
    marks = {mark: [i for i, line in enumerate(lines) if line.strip() == mark] for mark in DROPDOWN}
    if any(len(found) != 1 for found in marks.values()) or marks[start][0] > marks[end][0]:
        raise SystemExit(f"device_report.yml: expected one '{start}' line, then one '{end}' line")
    first, last = marks[start][0], marks[end][0]
    indent = lines[first][: len(lines[first]) - len(lines[first].lstrip())]
    titles = sorted(plain_title(info) for info in registry.available_integrations())
    options = [f"{indent}- {title}\n" for title in titles]
    return "".join([*lines[: first + 1], *options, *lines[last:]])


def main(argv: list[str] | None = None, registry: AdapterRegistry | None = None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when CODEOWNERS or the device report is out of date")
    args = parser.parse_args(argv)

    registry = registry or AdapterRegistry.discover()
    text = generate(registry, repo)
    manifest = json.loads((repo / MANIFEST.relative_to(REPO)).read_text()).get("codeowners")
    if manifest != [f"@{handle}" for handle in REPO_MAINTAINERS]:
        print(f"error: manifest.json codeowners {manifest} don't match REPO_MAINTAINERS; edit one", file=sys.stderr)
        return 1
    form = repo / DEVICE_REPORT.relative_to(REPO)
    outputs = {
        repo / CODEOWNERS.relative_to(REPO): text,
        form: generate_device_report(form.read_text(), registry),
    }
    stale = [path for path, new in outputs.items() if not path.exists() or path.read_text() != new]
    if args.check and stale:
        for path in stale:
            print(f"error: {path.relative_to(repo)} out of date; run scripts/gen_codeowners.py", file=sys.stderr)
        return 1
    for path in stale:
        path.write_text(outputs[path])
    return 0


if __name__ == "__main__":
    sys.exit(main())
