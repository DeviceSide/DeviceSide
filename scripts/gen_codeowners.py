#!/usr/bin/env python3
"""Generate .github/CODEOWNERS from each integration's `IntegrationInfo.maintainers`.

The repo maintainers own everything (`*`, first), so shared code, shared docs and the generated pages' shared inputs
(`docs/models.yaml`) need their review. Each integration's package then goes to its maintainers, with the repo
maintainers appended so they can always approve: its adapter package, its tests and test fixture, and its doc bundle
(`docs/integrations/<key>/`, its test records included), each only once it exists. GitHub reads the last matching
line, so the per-integration lines must follow `*`.

`REPO_MAINTAINERS` also has to match `manifest.json`'s `codeowners`, which HA shows as the integration's owners; the
script checks that, in both modes, and leaves the manifest for a hand edit.

Usage: scripts/gen_codeowners.py [--check]

--check exits 1 when the committed file differs from what this generates.
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from custom_components.deviceside.core.registry import AdapterRegistry  # noqa: E402

CODEOWNERS = REPO / ".github" / "CODEOWNERS"
MANIFEST = REPO / "custom_components" / "deviceside" / "manifest.json"
# The repo maintainers: admin on the repo, owners of shared code, merging every PR. The one source of their handles;
# manifest.json's codeowners must match it.
REPO_MAINTAINERS: tuple[str, ...] = ("jasonmx",)
# Each integration's paths, relative to the repo, by its key; a path that doesn't exist yet is left out.
PATHS = (
    "custom_components/deviceside/integrations/{key}/",
    "tests/integrations/{key}/",
    "tests/fixtures/{key}.py",
    "docs/integrations/{key}/",
)


def owners(maintainers: tuple[str, ...]) -> str:
    return " ".join(f"@{handle}" for handle in dict.fromkeys([*maintainers, *REPO_MAINTAINERS]))


def generate(registry: AdapterRegistry, repo: Path = REPO) -> str:
    if not REPO_MAINTAINERS:
        raise SystemExit("REPO_MAINTAINERS is empty: shared code would have no owner")
    lines = [
        "# Generated by scripts/gen_codeowners.py from each integration's IntegrationInfo.maintainers. Do not edit;",
        "# run the script. The last matching line wins, so everything not listed below is the repo maintainers'.",
        f"* {owners(())}",
    ]
    for key in sorted(registry.integrations):
        info = registry.integrations[key]
        if not info.available:
            raise SystemExit(f"{key} failed to import ({info.unavailable_reason}); its maintainers can't be read")
        paths = [path.format(key=key) for path in PATHS]
        if not (repo / paths[0]).is_dir():
            raise SystemExit(f"{key}: no package at {paths[0]}")
        lines.append("")
        lines += [f"/{path} {owners(info.maintainers)}" for path in paths if (repo / path).exists()]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None, registry: AdapterRegistry | None = None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when CODEOWNERS is out of date")
    args = parser.parse_args(argv)

    text = generate(registry or AdapterRegistry.discover(), repo)
    manifest = json.loads((repo / MANIFEST.relative_to(REPO)).read_text()).get("codeowners")
    if manifest != [f"@{handle}" for handle in REPO_MAINTAINERS]:
        print(f"error: manifest.json codeowners {manifest} don't match REPO_MAINTAINERS; edit one", file=sys.stderr)
        return 1
    path = repo / CODEOWNERS.relative_to(REPO)
    current = path.read_text() if path.exists() else None
    if current == text:
        return 0
    if args.check:
        print("error: .github/CODEOWNERS out of date; run scripts/gen_codeowners.py", file=sys.stderr)
        return 1
    path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
