"""The standard lights: the zigbee-herdsman-converters (ZHC) light definitions whose converter for every key DeviceSide
publishes is ZHC's standard one, with no flag or override touching a DeviceSide call. A catalog table, keyed on the
definition model and carrying the Zigbee strings ZHC matches each one on, so any Zigbee integration can read it.
Zigbee2MQTT's `standard_light` class keys on a light's definition model being a member
(integrations/zigbee2mqtt/families/__init__.py, the rule; its classes.py, the levels); why, and how the table is
bumped: docs/integrations/zigbee2mqtt/internals.md, Standard lights.

Between the markers, generated by `scripts/zhc_table.py --pin <ZHC release>`, which rewrites only that block. Outside
them, hand-kept: `EXCLUDED` and `KEPT` (docs/evidence.md, Documented, a standard converter's call). Stdlib only and
no I/O, as the generator reads it at a git tag by running it alone.
"""

from dataclasses import dataclass
from typing import NamedTuple

STANDARD_LIGHT = "standard_light"


class Light(NamedTuple):
    """A member's row: its vendor, whether its light exposes color_hs, and the Zigbee strings ZHC matches its
    definition on: `zigbee_models`, model IDs on any manufacturer (ZHC's zigbeeModel), and `fingerprints`, each a
    (model ID, manufacturer name) pair, "" where ZHC gives none (its other fingerprint fields aren't kept)."""

    vendor: str
    color_hs: bool
    zigbee_models: tuple[str, ...]
    fingerprints: tuple[tuple[str, str], ...]


@dataclass(frozen=True, slots=True)
class Excluded:
    """A split-off: a definition model a Zigbee2MQTT or ZHC issue or PR reports failing a call DeviceSide sends
    (`action`), excluded on the report alone (`source`, an https URL). It stays in `other`, in Labs, on every action.
    The identity is the definition model, the narrowest the rules read: a report that narrows it to firmware still
    excludes the model."""

    model: str
    action: str
    source: str


@dataclass(frozen=True, slots=True)
class Kept:
    """A departure a maintainer kept: a model a ZHC bump took off MODELS whose features shipped outside Labs in a full
    release, reviewed and kept, with the reason. `light` is its row as MODELS held it."""

    model: str
    light: Light
    reason: str


